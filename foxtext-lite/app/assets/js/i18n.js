  var LANGS = ['zh-CN', 'en', 'ja'];
  var NATIVE_NAMES = { 'zh-CN': '简体中文', en: 'English', ja: '日本語' };

  /**
   * Detect the preferred locale from navigator.language.
   * @return {string} one of LANGS
   */
  function detect() {
    var raw = (typeof navigator !== 'undefined' && (navigator.language || navigator.userLanguage)) || 'en';
    var lower = String(raw).toLowerCase();
    if (lower.indexOf('zh') === 0) return 'zh-CN';
    if (lower.indexOf('ja') === 0) return 'ja';
    if (lower.indexOf('en') === 0) return 'en';
    return 'en';
  }

